"""
smoke_test.py - check that the toolchain works in this environment without
touching the real repo. Copies the repo to a temp dir, composes a throwaway
strip of plain shapes, renders it, validates it and builds the site.

    python3 tools/smoke_test.py            # prints the temp dir it used
"""
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]


def run(*args, cwd):
    r = subprocess.run([sys.executable, *args], cwd=cwd, capture_output=True, text=True)
    print(r.stdout.strip())
    if r.returncode:
        print(r.stderr)
        sys.exit(f"smoke test failed at: {' '.join(args)}")


def main():
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="comic-smoke-"))
    repo = tmp / "repo"
    shutil.copytree(ROOT, repo, ignore=shutil.ignore_patterns(".git", "docs", "episodes"))
    ep = repo / "episodes" / "0001"
    ep.mkdir(parents=True)

    sys.path.insert(0, str(repo / "tools"))
    from comic import Strip

    s = Strip(width=1200, height=420, cols=3, title="Smoke test")
    blob = '<circle r="40" fill="#8ab"/><circle cx="-14" cy="-8" r="5"/><circle cx="14" cy="-8" r="5"/>'
    for i, p in enumerate(s.panels):
        p.background(["#f3efe6", "#e8f0f3", "#f6e9e9"][i])
        p.add(blob, x=p.rect.w * 0.3, y=p.rect.h * 0.7)
        p.add(blob, x=p.rect.w * 0.72, y=p.rect.h * 0.72, flip=True)
    s.panels[0].caption("Testing, testing.")
    s.panels[0].balloon("Does the lettering wrap properly inside the balloon?", 20, 60,
                        tail=(s.panels[0].rect.w * 0.3, s.panels[0].rect.h * 0.62))
    s.panels[1].balloon("Hmm.", 200, 40, tail=(s.panels[1].rect.w * 0.72, 230), kind="thought")
    s.panels[2].balloon("IT WORKS!", 120, 40, tail=(s.panels[2].rect.w * 0.72, 250), kind="shout")
    s.panels[2].sfx("BOINK", 30, 120)
    s.save(ep / "comic.svg")
    (ep / "meta.json").write_text(json.dumps({
        "number": 1, "title": "Smoke Test", "date": "2026-01-01", "status": "published",
        "alt": "Three panels of two round blue blobs talking; a toolchain test, not a real episode.",
        "transcript": ["Caption: Testing, testing.", "Blob: Does the lettering wrap?", "Blob: IT WORKS!"],
        "note": "Generated by tools/smoke_test.py.",
    }))
    run("tools/render.py", str(ep / "comic.svg"), cwd=repo)
    run("tools/validate.py", str(ep), cwd=repo)
    run("tools/build_site.py", cwd=repo)
    for f in ("docs/index.html", "docs/ep/0001/index.html", "docs/archive/index.html", "docs/feed.xml"):
        assert (repo / f).exists(), f"missing {f}"
    print(f"SMOKE TEST PASSED -> {repo}")
    print(f"look at: {ep / 'comic.png'}")


if __name__ == "__main__":
    main()
